/*
 * Generate /ads.txt at the site root from assets/js/site.config.js.
 *
 * Run: node scripts/generate-ads-txt.js
 *
 * Google's official format (confirmed in AdSense help):
 *   google.com, pub-<16 digits>, DIRECT, f08c47fec0942fa0
 *
 * IMPORTANT: never ship a fake/example pub ID. An invalid ID tells Google
 * the domain is authorized for the WRONG publisher, which is worse than
 * having no ads.txt at all. When no real ID is configured we emit a
 * comment-only file explaining the situation — harmless and IAB-valid.
 */

const fs = require("fs");
const path = require("path");
const CONFIG = require("../assets/js/site.config.js");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "ads.txt");
const PUB_ID = (CONFIG.adsense && CONFIG.adsense.pubId ? String(CONFIG.adsense.pubId) : "").trim();
const GOOGLE_AUTHORITY_ID = "f08c47fec0942fa0";

let content;
if (/^pub-\d{16}$/.test(PUB_ID)) {
  content = `# ads.txt for thetestlibrary.app\n# Generated by scripts/generate-ads-txt.js — do not edit by hand.\ngoogle.com, ${PUB_ID}, DIRECT, ${GOOGLE_AUTHORITY_ID}\n`;
  console.log(`ads.txt generated with publisher ${PUB_ID}`);
} else {
  content = [
    "# ads.txt for thetestlibrary.app",
    "#",
    "# No AdSense publisher ID is configured yet, so there are no authorized",
    "# seller entries. This placeholder is intentional: publishing a fake or",
    "# example pub ID would authorize the wrong seller and is worse than none.",
    "#",
    "# To activate:",
    "#   1. Set adsense.pubId in assets/js/site.config.js to your real ID",
    "#      (16 digits, e.g. pub-1234567890123456)",
    "#   2. Run: node scripts/generate-ads-txt.js",
    "#",
    "# The generated line will be:",
    "# google.com, pub-<your 16 digits>, DIRECT, f08c47fec0942fa0",
    "#",
    "# Note: ads.txt must live at the domain root (https://thetestlibrary.app/ads.txt).",
    "#",
  ].join("\n");
  console.log("ads.txt placeholder generated (no real pub ID configured)");
}

fs.writeFileSync(OUT, content, "utf8");
console.log(`wrote ${OUT}`);
